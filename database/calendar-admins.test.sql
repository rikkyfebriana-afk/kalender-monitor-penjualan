begin;
do $$
declare owner_uid uuid; member_uid uuid; affected integer; blocked boolean;
begin
 select owner_id into owner_uid from public.calendar_team where id=1;
 select id into member_uid from auth.users where id<>owner_uid limit 1;
 if member_uid is null then raise exception 'No viewer fixture'; end if;
 perform set_config('request.jwt.claim.sub',member_uid::text,true);
 perform set_config('role','authenticated',true);
 update public.calendar_team set revision=revision where id=1;
 get diagnostics affected=row_count;
 if affected<>0 then raise exception 'Viewer could edit'; end if;
 blocked:=false;
 begin insert into public.calendar_admins(user_id,granted_by) values(member_uid,member_uid);
 exception when insufficient_privilege then blocked:=true; end;
 if not blocked then raise exception 'Viewer self-promoted'; end if;
 perform set_config('role','none',true);
 perform set_config('request.jwt.claim.sub',owner_uid::text,true);
 perform set_config('role','authenticated',true);
 insert into public.calendar_admins(user_id,granted_by) values(member_uid,owner_uid);
 perform set_config('role','none',true);
 perform set_config('request.jwt.claim.sub',member_uid::text,true);
 perform set_config('role','authenticated',true);
 update public.calendar_team set revision=revision where id=1;
 get diagnostics affected=row_count;
 if affected<>1 then raise exception 'Admin cannot edit'; end if;
 blocked:=false;
 begin update public.calendar_team set owner_id=member_uid where id=1;
 exception when insufficient_privilege then blocked:=true; end;
 if not blocked then raise exception 'Admin can take ownership'; end if;
 delete from public.calendar_admins where user_id=member_uid;
 get diagnostics affected=row_count;
 if affected<>0 then raise exception 'Admin can manage roles'; end if;
 perform set_config('role','none',true);
 perform set_config('request.jwt.claim.sub',owner_uid::text,true);
 perform set_config('role','authenticated',true);
 delete from public.calendar_admins where user_id=member_uid;
 get diagnostics affected=row_count;
 if affected<>1 then raise exception 'Owner cannot revoke'; end if;
 perform set_config('role','none',true);
 perform set_config('request.jwt.claim.sub',member_uid::text,true);
 perform set_config('role','authenticated',true);
 update public.calendar_team set revision=revision where id=1;
 get diagnostics affected=row_count;
 if affected<>0 then raise exception 'Revoked admin can edit'; end if;
 perform set_config('role','none',true);
end $$;
rollback;